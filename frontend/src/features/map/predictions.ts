import type { Bbox } from './region'

const API = (import.meta.env.VITE_API_BASE_URL ?? '/api').replace(/\/$/, '')
const SNAPSHOT = '/prediccion' // frontend/public/prediccion (generated by `flask prediction-snapshot`)

export type ZoneProps = {
  zona_id: number
  prob: number | null
  nivel: 'bajo' | 'moderado' | 'alto'
  base: number | null
  p50: number | null
  p90: number | null
  valor: number | null
  anomalia: 0 | 1 | null
}
export type ZoneFeature = { type: 'Feature'; id: number; properties: ZoneProps; geometry: { type: 'Polygon'; coordinates: number[][][] } }
export type ZoneCollection = {
  type: 'FeatureCollection'
  features: ZoneFeature[]
  semana: string
  resumen: { zonas: number; prob_max: number | null; zonas_alto: number }
  fuente?: string
  horizonte_semanas?: number
}
export type CurrentForecast = {
  generado_utc: string
  datos_hasta: string
  aviso: string
  semana_en_curso: ZoneCollection
  semana_proxima: ZoneCollection
}

async function getJson<T>(apiPath: string, snapshotPath: string, signal: AbortSignal): Promise<T | null> {
  for (const url of [`${API}${apiPath}`, `${SNAPSHOT}${snapshotPath}`]) {
    try {
      const r = await fetch(url, { signal })
      if (r.ok && (r.headers.get('content-type') ?? '').includes('json')) return (await r.json()) as T
    } catch (e) {
      if ((e as Error).name === 'AbortError') throw e
    }
  }
  return null
}

export type SeriesRow = {
  semana: string
  fuente: 'historico' | 'vivo'
  zonas: number
  prob_max: number | null
  prob_media: number | null
  zonas_alto: number
  valor: number | null
  p90: number | null
  anomalias: number | null
}
export type ForecastSeries = { zonas: number[]; data: SeriesRow[] }

const bboxQuery = (b?: Bbox | null) =>
  b ? `lat_min=${b.south}&lat_max=${b.north}&lon_min=${b.west}&lon_max=${b.east}` : ''

export const getCurrentForecast = (signal: AbortSignal, bbox?: Bbox | null) =>
  getJson<CurrentForecast>(`/predictions?${bboxQuery(bbox)}`, '/current.json', signal)
export const getWeekForecast = (week: string, signal: AbortSignal, bbox?: Bbox | null) =>
  getJson<ZoneCollection>(`/predictions/week/${week}?${bboxQuery(bbox)}`, `/week/${week}.json`, signal)
/** Weekly series for a selected area (dashboard). API only (no static fallback for arbitrary areas). */
export async function getForecastSeries(bbox: Bbox | null, signal: AbortSignal, start = '2015-01-05', end?: string) {
  const q = `${bboxQuery(bbox)}&start=${start}${end ? `&end=${end}` : ''}`
  const r = await fetch(`${API}/predictions/series?${q}`, { signal })
  if (!r.ok) throw new Error(`/predictions/series ${r.status}`)
  return (await r.json()) as ForecastSeries
}
export async function getForecastValidation(signal: AbortSignal) {
  const r = await fetch(`${API}/predictions/validation`, { signal })
  if (!r.ok) throw new Error(`/predictions/validation ${r.status}`)
  return (await r.json()) as Record<string, unknown>
}

const pad = (n: number) => String(n).padStart(2, '0')
/** Monday (YYYY-MM-DD) of the week that contains `d`; weeks run Monday–Sunday like the model. */
export function mondayOf(d: Date): string {
  const m = new Date(d.getFullYear(), d.getMonth(), d.getDate() - ((d.getDay() + 6) % 7))
  return `${m.getFullYear()}-${pad(m.getMonth() + 1)}-${pad(m.getDate())}`
}

